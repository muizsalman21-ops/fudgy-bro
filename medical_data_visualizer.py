import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

df = pd.read_csv('medical_examination.csv')
df

# Add an overweight column
overwight = (df['weight'] / (df['height']/100)**2)
df['overweight'] = (overwight > 25).astype(int)
df

# Normalize data by making 0 always good and 1 always bad
df['cholesterol'] = (df['cholesterol'] > 1).astype(int)
df['gluc'] = (df['gluc'] > 1).astype(int)
df

# Draw the Categorical Plot in the draw_cat_plot function
def draw_cat_plot():
  df_cat = pd.melt(df,id_vars=['cardio'],value_vars=['cholesterol', 'gluc', 'smoke', 'alco', 'active', 'overweight'])
  df_cat = (df_cat.groupby(['cardio', 'variable', 'value']).size().reset_index(name='total'))
  fig = sns.catplot(data=df_cat,x='variable',y='total',hue='value',col='cardio',kind='bar').fig
  return fig
fig = draw_cat_plot()
fig

# Draw draw_heat_map function
def draw_heat_map():
  df_heat = df[(df['ap_lo'] <= df['ap_hi'])&(df['height'] >= df['height'].quantile(0.025))&(df['height'] <= df['height'].quantile(0.975))
  &(df['weight'] >= df['weight'].quantile(0.025))&(df['weight'] <= df['weight'].quantile(0.975))]
  corr = df_heat.corr()
  mask = np.triu(np.ones_like(corr, dtype=bool))
  fig, ax = plt.subplots(figsize=(12, 10))
  sns.heatmap(corr,mask=mask,annot=True,fmt=".1f",square=True)
  fig = ax.figure
  return fig
fig = draw_heat_map()
fig