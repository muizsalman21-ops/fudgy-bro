import numpy as np
# Make a function named calculate
def calculate(py_list):
    # Reshape the list into the 3x3 matrix
    matrix = np.array(py_list).reshape(3,3)
    # Calculate the statistics values
    mean_col = matrix.mean(axis=0)
    mean_row = matrix.mean(axis=1)
    mean_whole = matrix.mean()
    var_col = matrix.var(axis=0)
    var_row = matrix.var(axis=1)
    var_whole = matrix.var()
    stdev_col = matrix.std(axis=0)
    stdev_row = matrix.std(axis=1)
    stdev_whole = matrix.std()
    max_col = matrix.max(axis=0)
    max_row = matrix.max(axis=1)
    max_whole = matrix.max()
    min_col = matrix.min(axis=0)
    min_row = matrix.min(axis=1)
    min_whole = matrix.min()
    sum_col = matrix.sum(axis=0)
    sum_row = matrix.sum(axis=1)
    sum_whole = matrix.sum()
    return {'mean': [mean_col.tolist(), mean_row.tolist(), mean_whole],
            'variance': [var_col.tolist(), var_row.tolist(), var_whole],
            'standard deviation': [stdev_col.tolist(), stdev_row.tolist(), stdev_whole],
            'max': [max_col.tolist(), max_row.tolist(), max_whole],
            'min': [min_col.tolist(), min_row.tolist(), min_whole],
            'sum': [sum_col.tolist(), sum_row.tolist(), sum_whole]}
print(calculate([0,1,2,3,4,5,6,7,8]))