import pandas as pd

df = pd.read_csv('adult.data.csv', sep=';')
df.head()

# How many people of each race are represented in this dataset?
df['race'].value_counts()

# What is the average age of men?
df2 = df[df['sex']=='Male']
df2['age'].mean()

# What is the percentage of people who have a Bachelor's degree?
a = (df['education'] == 'Bachelors').sum()
b = len(df)
percentage = (a/b)*100
percentage

# What percentage of people with advanced education (Bachelors, Masters, or Doctorate) make more than 50K?
df3 = df[(df['education'] == 'Bachelors') | (df['education'] == 'Masters') | (df['education'] == 'Doctorate')]
df4 = df3[df3['salary'] == '>50K']
percent_50k = (len(df4)/len(df3))*100
percent_50k

# What percentage of people without advanced education make more than 50K?
df5 = df[(df['education'] != 'Bachelors') & (df['education'] != 'Masters') & (df['education'] != 'Doctorate')]
df6 = df5[df5['salary'] == '>50K']
percent_50k_no = (len(df6)/len(df5))*100
percent_50k_no

# What is the minimum number of hours a person works per week?
df['hours-per-week'].min()

# What percentage of the people who work the minimum number of hours per week have a salary of more than 50K?
df7 = df[df['hours-per-week'] == df['hours-per-week'].min()]
df8 = df7[df7['salary'] == '>50K']
percent_50k_min = (len(df8)/len(df7))*100
percent_50k_min

# What country has the highest percentage of people that earn >50K and what is that percentage?
df9 = df[df['salary'] == '>50K']
df10 = df9['native-country'].value_counts()
df11 = df['native-country'].value_counts()
df12 = df10/df11
df13 = pd.DataFrame(df12)
df13.columns = ['percentage']
df13.loc[df13['percentage'].idxmax()]

# Identify the most popular occupation for those who earn >50K in India
df14 = df[(df['native-country'] == 'India') & (df['salary'] == '>50K')]
df14['occupation'].value_counts()