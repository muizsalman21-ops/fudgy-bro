import pandas as pd
import matplotlib.pyplot as plt
import matplotlib.dates as mdates
import seaborn as sns

df = pd.read_csv('fcc-forum-pageviews.csv')
df['date'] = pd.to_datetime(df['date'])

# Make the date column as index
df = df.set_index('date')

# Cleaning data
df = df[(df['value']>=df['value'].quantile(0.025))&(df['value']<=df['value'].quantile(0.975))]

# Making draw_line_plot function
def draw_line_plot():
  fig,ax = plt.subplots(figsize=(10,5))
  ax.plot(df.index,df['value'])
  ax.set_title('Daily freeCodeCamp Forum Page Views 5/2016-12/2019')
  ax.set_xlabel('Date')
  ax.set_ylabel('Page Views')
  ax.xaxis.set_major_locator(mdates.MonthLocator(interval=6))
  ax.xaxis.set_major_formatter(mdates.DateFormatter('%Y-%m'))
  return

# Making draw_bar_plot function
df_bar = df.copy()
df_bar['year'] = df_bar.index.year
df_bar['month'] = df_bar.index.month_name()
months = ['January','February','March','April','May','June','July','August','September','October','November','December']
df_bar['month'] = pd.Categorical(df_bar['month'],categories=months,ordered=True)
df_bar = df_bar.groupby(['year', 'month'])['value'].mean().unstack()
def draw_bar_plot():
  fig = df_bar.plot(kind='bar', figsize=(10, 8))
  fig.set_ylabel('Average Page Views')
  return fig

# Making draw_box_plot function
df_box = df.copy()
df_box['year'] = df_box.index.year
df_box['month'] = df_box.index.month
def draw_box_plot():
  plt.close('all')
  fig, axes = plt.subplots(1,2,figsize=(15,5))
  sns.boxplot(x='year',y='value',data=df_box,ax=axes[0])
  axes[0].set_title('Year-wise Box Plot (Trend)')
  axes[0].set_xlabel('Year')
  axes[0].set_ylabel('Page Views')
  sns.boxplot(x='month',y='value',data=df_box,ax=axes[1])
  axes[1].set_title('Month-wise Box Plot (Seasonality)')
  axes[1].set_xlabel('Month')
  axes[1].set_ylabel('Page Views')
  axes[1].set_xticklabels(['Jan','Feb','Mar','Apr','May','Jun',
                           'Jul','Aug','Sep','Oct','Nov','Dec'])
  return fig